"""行业主题 ETF 识别：名称关键词白名单。

从 fund_etf_spot_em 全量 ETF 中，按名称关键词识别行业主题 ETF，并归类到统一行业名。
一个行业可有多个 ETF（如医疗ETF有5只），评分时按流通市值取代表 ETF。
"""

from __future__ import annotations

# 行业名 -> 名称匹配关键词（按重要性排序，命中任一即归入该行业）
# 注意：关键词需能稳定命中东财 ETF 名称，且不与宽基/跨境/债券/货币类冲突。
INDUSTRY_KEYWORDS: dict[str, list[str]] = {
    "银行": ["银行"],
    "证券": ["证券", "券商"],
    "保险": ["保险"],
    "半导体": ["半导体", "芯片"],
    "人工智能": ["人工智能", "AI"],
    "通信": ["通信", "5G"],
    "计算机": ["计算机", "软件", "云计算", "大数据"],
    "医药": ["医药", "创新药", "医疗", "生物医药", "医疗器械", "中药", "疫苗"],
    "消费": ["消费", "白酒", "食品饮料", "家电", "酒"],
    "新能源": ["新能源", "光伏", "电池", "储能", "锂电"],
    "汽车": ["汽车"],
    "军工": ["军工", "国防"],
    "房地产": ["房地产", "地产"],
    "煤炭": ["煤炭"],
    "钢铁": ["钢铁"],
    "有色金属": ["有色金属", "有色", "稀土", "黄金"],
    "化工": ["化工", "化学制品"],
    "传媒": ["传媒", "游戏", "影视"],
    "电子": ["电子"],
    "电力": ["电力", "绿电"],
    "机械": ["机械"],
    "环保": ["环保"],
    "农业": ["农业", "养殖", "畜牧"],
    "建筑": ["建筑"],
    "交通运输": ["交通运输", "物流", "航运"],
}

# 需排除的非行业主题 ETF 名称关键词（宽基/跨境/债券/货币/商品等）
# 命中任一即剔除，避免宽基指数（如沪深300ETF）被误判为行业。
EXCLUDE_KEYWORDS: list[str] = [
    "沪深", "中证500", "中证1000", "上证50", "科创50", "创业板",
    "A50", "A500", "MSCI", "标普", "纳斯达克", "恒生", "日经", "德国", "法国",
    "国债", "信用债", "城投债", "可转债", "货币", "黄金", "原油", "商品",
    "红利", "低波", "价值", "成长", "质量", "300", "500",
]


def identify_industries(names: list[str]) -> dict[str, str]:
    """将 ETF 名称映射到行业名，返回 {etf_name: industry}。

    优先按 INDUSTRY_KEYWORDS 精确归类；命中排除词或未命中任何行业的 ETF 不返回。
    同一 ETF 名称命中多个行业时取第一个命中行业（关键词列表按重要性排序）。
    """
    result: dict[str, str] = {}
    for name in names:
        nm = str(name or "").strip()
        if not nm:
            continue
        if any(k in nm for k in EXCLUDE_KEYWORDS):
            continue
        for industry, kws in INDUSTRY_KEYWORDS.items():
            if any(k in nm for k in kws):
                result[nm] = industry
                break
    return result
