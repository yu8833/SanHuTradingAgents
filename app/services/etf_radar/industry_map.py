def identify_industries(names: list[str]) -> dict[str, str]:
    """将 ETF 名称映射到行业名，返回 {etf_name: industry}。

    优先按 INDUSTRY_KEYWORDS 精确归类；命中排除词或未命中任何行业的 ETF 不返回。
    同一 ETF 名称命中多个行业时取第一个命中行业（关键词列表按重要性排序）。
    """
    result: dict[str, str] = {}
    for name in names:
        nm = str(name or "").strip()
        if not nm:
            continue
        if any(k in nm for k in EXCLUDE_KEYWORDS):
            continue
        for industry, kws in INDUSTRY_KEYWORDS.items():
            if any(k in nm for k in kws):
                result[nm] = industry
                break
    return result
