def get_template(strategy_id: str) -> dict | None:
    """按策略 id 取模板（无则 None）。"""
    return STRATEGY_TEMPLATES.get(strategy_id)


def get_route_hint(strategy_id: str) -> str:
    """取策略的环境适配提示；未定义返回空串。"""
    t = STRATEGY_TEMPLATES.get(strategy_id)
    return (t or {}).get("route_hint", "")


def build_strategy_prompt(strategy_id: str) -> str:
    """组装完整策略 prompt（描述+工具+步骤+评分+输出+环境适配+结论约束），供对话注入。"""
    t = STRATEGY_TEMPLATES.get(strategy_id)
    if not t:
        return ""
    parts = [
        f"【{t['name']}·策略说明】{t['description']}",
        f"【可用工具】{'、'.join(t['tools'])}",
        "【判断步骤】" + "；".join(t["steps"]),
        f"【评分锚定】{t['score']}",
        f"【结论输出】{t['output']}",
    ]
    hint = t.get("route_hint")
    if hint:
        parts.append(hint)
    if t.get("constraint"):
        parts.append(f"【结论约束】{t['constraint']}")
    return "\n".join(parts)