def normalize_to_ths(local_industry: str | None) -> str:
    """本地行业名 → 同花顺 90 行业。未命中返回「其他」。

    若输入本身已是同花顺 90 行业名，则直接返回（幂等）。
    """
    name = (local_industry or "").strip()
    if not name:
        return OTHER_THS
    if name in THS_90_INDUSTRIES:
        return name
    ths = LOCAL_TO_THS.get(name)
    if ths is None:
        logger.debug(f"行业名未映射到同花顺 90 行业: {name!r}（已归为「其他」）")
        return OTHER_THS
    return ths


def is_ths_industry(name: str) -> bool:
    """判断给定名称是否属于同花顺 90 行业。"""
    return name in THS_90_INDUSTRIES


def resolve_stock_ths_industry(info: dict) -> str:
    """从 stock_basic_info 单条记录解析同花顺行业。

    Args:
        info: {"industry": ..., "source": ...}

    优先用本地 industry 归一；若本身已是同花顺行业名则直接返回。
    """
    industry = (info.get("industry") or "").strip()
    if not industry:
        return OTHER_THS
    if industry in THS_90_INDUSTRIES:
        return industry
    return normalize_to_ths(industry)
